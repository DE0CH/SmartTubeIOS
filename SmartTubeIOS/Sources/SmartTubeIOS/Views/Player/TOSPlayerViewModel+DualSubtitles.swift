import SmartTubeIOSCore
import WebKit
import os

private let dualLog = Logger(subsystem: appSubsystem, category: "TOSDualSubtitles")

// MARK: - Dual subtitles over the TOS (embed) player
//
// The embed shows YouTube's own captions, which can't carry furigana or a second line. When
// the video has a Japanese track, the caption track comes from the app's own InnerTube player
// request instead, `CaptionsManager` loads it as dual subtitles (DualSubtitles.swift), the
// cue follows the embed's `tick` time, TOSPlayerView draws `DualCaptionCueView` over the web
// view, and the embed's caption window is hidden so the two don't overlap.

extension TOSPlayerViewModel {

    /// Starts loading the Japanese track for this video, once. Does nothing when dual
    /// subtitles or "turn on Japanese captions automatically" are off.
    func loadDualSubtitles() {
        guard dualSubtitlesTask == nil, let dual = settings.dualSubtitleOptions, settings.autoJapaneseCaptions else {
            return
        }
        let videoId = videoId
        let api = api
        dualSubtitlesTask = Task { [weak self] in
            guard let info = try? await api.fetchPlayerInfo(videoId: videoId), !Task.isCancelled, let self else {
                return
            }
            let ja = info.captionTracks.filter(DualSubtitleOptions.applies(to:))
            guard let track = ja.first(where: { !$0.isAutoGenerated }) ?? ja.first else {
                dualLog.notice("[dualSubs] no Japanese caption track for \(videoId, privacy: .public)")
                return
            }
            dualLog.notice("[dualSubs] loading \(track.id, privacy: .public) for \(videoId, privacy: .public)")
            self.captionsManager.availableCaptions = info.captionTracks
            self.captionsManager.selectCaption(track, currentTime: self.currentTime, dual: dual)
        }
    }

    /// Called on every embed `tick`: moves the cue along and, once our captions have cues,
    /// hides the embed's caption window.
    func updateDualSubtitles(at time: Double) {
        guard !captionsManager.captionCues.isEmpty else { return }
        captionsManager.updateCaptionCue(for: time)
        if !embedCaptionsHidden, embedFrameInfo != nil {
            embedCaptionsHidden = true
            eval("hideEmbedCaptions", Self.hideEmbedCaptionsJS)
        }
    }

    static let hideEmbedCaptionsJS = """
        (function () {
          if (document.getElementById('st-dual-hide-cc')) return;
          var s = document.createElement('style');
          s.id = 'st-dual-hide-cc';
          s.textContent = '.ytp-caption-window-container, .caption-window { display: none !important; }';
          document.documentElement.appendChild(s);
        })();
        """
}
